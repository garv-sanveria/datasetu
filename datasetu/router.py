"""Dynamic Router and API synthesis module for DataSetu.

What this module does:
1. Spawns a production FastAPI application with OpenAPI 3.1 specification and Swagger UI.
2. Dynamically generates Pydantic v2 data models using `create_model` reflecting the in-memory
   DuckDB schema and column types.
3. Serves the required REST endpoints:
   - `/v1/data` (and `/data`): 1-indexed paginated data queries with column-level filtering,
     comparators (__gte, __lte), full-text search (`q`), sorting, and field selection.
   - `/v1/data/summary` (and `/data/summary`): Column-level distributions and metric aggregations.
   - `/v1/schema` (and `/schema`): In-memory types, column listings, and dynamic Pydantic JSON schemas.
   - `/v1/report` (and `/report`): Full NormalizationReport covering preambles, encoding, conversions,
     and LGD resolution statistics.
   - `/v1/changelog` (and `/changelog`): Semver mutation history and atomic swap logs.
   - `/` (and `/demo`): Self-contained, 100% offline Before/After comparison web UI.
4. Configures CORS and exposes the raw OpenAPI JSON schema for SDK generation.

Why it exists:
Data portals produce static CSV/XLSX dumps that cannot be queried or integrated into modern developer
workflows. DataSetu synthesizes a live, queryable REST API instantly from memory.

How it connects to other modules:
- Takes a populated `DatasetStore` from `db.py`.
- Generates dynamic schemas and routes.
- The OpenAPI JSON schema generated by FastAPI is passed directly to `sdk_generator.py` to compile
  a typed Python client.
"""

from __future__ import annotations

import re
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Type

from fastapi import FastAPI, HTTPException, Query, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, HTMLResponse, Response
from pydantic import BaseModel, Field, create_model

from datasetu.db import DatasetStore, _safe_sql_ident
from datasetu.security import (
    RateLimitMiddleware,
    RequestSizeLimitMiddleware,
    SecurityHeadersMiddleware,
    verify_safe_file_path,
)


def _build_pydantic_record_model(schema: List[Dict[str, str]]) -> Type[BaseModel]:
    """Dynamically construct a Pydantic v2 model from in-memory DuckDB column types."""
    field_definitions: Dict[str, Any] = {}

    for idx, col in enumerate(schema):
        col_name = col["name"]
        col_type = col["type"].upper()

        if any(t in col_type for t in ("INT", "BIGINT", "SMALLINT", "TINYINT")):
            py_type = Optional[int]
        elif any(t in col_type for t in ("FLOAT", "DOUBLE", "DECIMAL", "REAL", "NUMERIC")):
            py_type = Optional[float]
        elif "BOOL" in col_type:
            py_type = Optional[bool]
        else:
            py_type = Optional[str]

        # Generate a valid Python identifier for internal field name
        safe_identifier = re.sub(r"[^\w]", "_", col_name).strip("_")
        if not safe_identifier or safe_identifier[0].isdigit():
            safe_identifier = f"field_{idx}_{safe_identifier}"

        field_definitions[safe_identifier] = (
            py_type,
            Field(default=None, alias=col_name, serialization_alias=col_name),
        )

    return create_model("DatasetRecord", **field_definitions)


def build_app(store: DatasetStore, source_info: Optional[Dict[str, Any]] = None) -> FastAPI:
    """Build and configure a FastAPI application over an active DatasetStore."""
    app = FastAPI(
        title="DataSetu Engine API",
        version=store.version,
        description=(
            "Instant REST API and Bharat Entity Intelligence engine for Indian public data.\n"
            "Compiled deterministically with DuckDB columnar execution and LGD gazetteer crosswalk."
        ),
        docs_url="/docs",
        redoc_url="/redoc",
        openapi_url="/openapi.json",
    )

    # 1. Defense-in-depth Security & Hardening Middlewares
    app.add_middleware(SecurityHeadersMiddleware)
    app.add_middleware(RateLimitMiddleware, max_requests=300, window_seconds=60)
    app.add_middleware(RequestSizeLimitMiddleware, max_bytes=10 * 1024 * 1024)

    # 2. CORS configuration for local developer tools and offline web interfaces
    app.add_middleware(
        CORSMiddleware,
        allow_origins=["*"],
        allow_credentials=True,
        allow_methods=["GET", "POST", "HEAD", "OPTIONS"],
        allow_headers=["*"],
    )

    # Attach store and source metadata
    app.state.store = store
    app.state.source_info = source_info or {}
    record_model = _build_pydantic_record_model(store.schema())
    app.state.record_model = record_model

    meta_model = create_model(
        "ResponseMeta",
        total=(int, Field(..., description="Total matching records")),
        page=(int, Field(..., description="Current page number (1-indexed)")),
        limit=(int, Field(..., description="Records per page")),
        pages=(int, Field(..., description="Total pages available")),
        version=(str, Field(..., description="Dataset semver version")),
        query_ms=(float, Field(..., description="Query execution latency in milliseconds")),
    )
    response_model = create_model(
        "DataResponse",
        data=(List[record_model], Field(..., description="List of dataset records")),  # type: ignore
        meta=(meta_model, Field(..., description="Pagination and query metadata")),
    )
    app.state.response_model = response_model

    # 1. Self-contained Demo UI & Presentation Deck
    @app.get("/", response_class=HTMLResponse, include_in_schema=False)
    @app.get("/demo", response_class=HTMLResponse, include_in_schema=False)
    def serve_demo_page():
        html_file = Path(__file__).parent / "static" / "index.html"
        if not html_file.exists():
            return HTMLResponse("<h1>DataSetu Engine API</h1><p>Visit <a href='/docs'>/docs</a> for Swagger UI.</p>")
        return HTMLResponse(
            content=html_file.read_text(encoding="utf-8"),
            headers={
                "Cache-Control": "no-cache, no-store, must-revalidate",
                "Pragma": "no-cache",
                "Expires": "0",
            },
        )

    @app.get("/deck", response_class=HTMLResponse, include_in_schema=False)
    def serve_deck_page():
        deck_file = Path(__file__).parent.parent / "docs" / "pitch_deck.html"
        if deck_file.exists():
            return HTMLResponse(content=deck_file.read_text(encoding="utf-8"))
        return HTMLResponse("<h1>Presentation deck not found</h1>")

    @app.get("/download/ppt", include_in_schema=False)
    @app.get("/download/deck", include_in_schema=False)
    def download_ppt():
        allowed_dir = (Path(__file__).parent.parent / "docs").resolve()
        target_file = allowed_dir / "DataSetu_DevForge_Finals.pptx"
        try:
            safe_file = verify_safe_file_path(target_file, allowed_dir)
        except PermissionError:
            raise HTTPException(status_code=403, detail="Access denied: directory traversal prohibited")
        except FileNotFoundError:
            raise HTTPException(status_code=404, detail="PPTX file not found")

        return FileResponse(
            path=str(safe_file),
            filename="DataSetu_DevForge_Finals.pptx",
            media_type="application/vnd.openxmlformats-officedocument.presentationml.presentation",
        )

    # 2. Health & Heartbeat
    @app.get("/health", tags=["System"])
    @app.get("/v1/health", tags=["System"])
    def get_health():
        return {
            "status": "healthy",
            "version": store.version,
            "columns": len(store.get_columns()),
            "source_info": app.state.source_info,
        }

    # 3. Primary Data Endpoint
    @app.get(
        "/v1/data",
        tags=["Data"],
        summary="Query paginated dataset with filters and full-text search",
        response_description="Paginated records with sub-millisecond query metadata",
        responses={200: {"model": response_model}},
    )
    @app.get(
        "/data",
        tags=["Data"],
        include_in_schema=False,
    )
    def query_dataset(
        request: Request,
        page: int = Query(1, ge=1, description="1-indexed page number (page=1 returns first records)"),
        limit: int = Query(50, ge=1, le=1000, description="Records per page (max 1000)"),
        sort: Optional[str] = Query(None, description="Sort column (prefix with '-' for descending)"),
        fields: Optional[str] = Query(None, description="Comma-separated column names to return"),
        q: Optional[str] = Query(None, description="Full-text search query across all string columns"),
        format: Optional[str] = Query("json", description="Output format: json, csv, parquet, ndjson"),
    ):
        reserved_params = {"page", "limit", "sort", "fields", "q", "format"}
        filters: Dict[str, Any] = {}

        # Extract dynamic column filters
        for param_key, param_val in request.query_params.items():
            if param_key not in reserved_params and param_val != "":
                # Try parsing numeric filters for __gte and __lte
                if param_key.endswith("__gte") or param_key.endswith("__lte"):
                    try:
                        parsed_val = float(param_val) if "." in param_val else int(param_val)
                        filters[param_key] = parsed_val
                    except ValueError:
                        filters[param_key] = param_val
                else:
                    filters[param_key] = param_val

        # Input validation & sanitization
        if q and len(q) > 256:
            raise HTTPException(status_code=400, detail="Search query 'q' cannot exceed 256 characters.")
        if fields and len(fields) > 1000:
            raise HTTPException(status_code=400, detail="Requested fields parameter exceeds maximum length.")

        field_list = [f.strip() for f in fields.split(",") if f.strip()] if fields else None
        export_fmt = (format or "json").lower().strip()

        # Multi-Format Streaming Exports (Crushing data.gov.in static export limits)
        if export_fmt == "csv":
            try:
                table, _, query_ms = store.query_arrow(
                    filters=filters, sort=sort, page=page, limit=limit, fields=field_list, q=q
                )
                csv_bytes = store.export_csv(table)
                return Response(
                    content=csv_bytes,
                    media_type="text/csv",
                    headers={
                        "Content-Disposition": f'attachment; filename="datasetu_export_p{page}.csv"',
                        "X-Query-Latency-MS": str(query_ms),
                    },
                )
            except ValueError as err:
                raise HTTPException(status_code=400, detail=str(err))

        elif export_fmt == "parquet":
            try:
                table, _, query_ms = store.query_arrow(
                    filters=filters, sort=sort, page=page, limit=limit, fields=field_list, q=q
                )
                parquet_bytes = store.export_parquet(table)
                return Response(
                    content=parquet_bytes,
                    media_type="application/octet-stream",
                    headers={
                        "Content-Disposition": f'attachment; filename="datasetu_export_p{page}.parquet"',
                        "X-Query-Latency-MS": str(query_ms),
                    },
                )
            except ValueError as err:
                raise HTTPException(status_code=400, detail=str(err))

        elif export_fmt in ("ndjson", "jsonl"):
            try:
                result = store.query(
                    filters=filters, sort=sort, page=page, limit=limit, fields=field_list, q=q
                )
                ndjson_str = store.export_ndjson(result.rows)
                return Response(
                    content=ndjson_str,
                    media_type="application/x-ndjson",
                    headers={"X-Query-Latency-MS": str(result.query_ms)},
                )
            except ValueError as err:
                raise HTTPException(status_code=400, detail=str(err))

        # Default JSON response
        try:
            result = store.query(
                filters=filters,
                sort=sort,
                page=page,
                limit=limit,
                fields=field_list,
                q=q,
            )
        except ValueError as err:
            raise HTTPException(status_code=400, detail=str(err))

        pages = max(1, (result.total + limit - 1) // limit)
        return {
            "data": result.rows,
            "meta": {
                "total": result.total,
                "page": page,
                "limit": limit,
                "pages": pages,
                "version": store.version,
                "query_ms": result.query_ms,
            },
        }

    # 4. Summary & Distribution Aggregations
    @app.get(
        "/v1/data/summary",
        tags=["Analytics"],
        summary="Dataset summary statistics and optional metric aggregations",
    )
    @app.get(
        "/data/summary",
        tags=["Analytics"],
        include_in_schema=False,
    )
    def get_summary(
        group_by: Optional[str] = Query(None, description="Column name to group aggregations by"),
        metric: Optional[str] = Query(None, description="Metric aggregation in 'func:col' format, e.g. 'sum:expenditure'"),
    ):
        try:
            res = store.summary(group_by=group_by, metric=metric)
            res["version"] = store.version
            return res
        except ValueError as err:
            raise HTTPException(status_code=400, detail=str(err))

    # 5. Schema & Pydantic Definitions
    @app.get(
        "/v1/schema",
        tags=["Metadata"],
        summary="Dynamic dataset schema, DuckDB types, and OpenAPI Pydantic model",
    )
    @app.get(
        "/schema",
        tags=["Metadata"],
        include_in_schema=False,
    )
    def get_schema():
        return {
            "version": store.version,
            "columns": store.schema(),
            "pydantic_schema": record_model.model_json_schema(),
        }

    # 5b. National Sectors Distribution (Directly modeled after data.gov.in sectors)
    @app.get(
        "/v1/sectors",
        tags=["Metadata"],
        summary="Distinct government sectors and record distribution in active dataset",
    )
    def list_sectors():
        col = store.resolve_column("sector")
        if not col:
            return {"sectors": [], "total_sectors": 0}
        safe_col = _safe_sql_ident(col)
        sql = f"SELECT {safe_col} as sector, COUNT(*) as count FROM {store.table_name} GROUP BY {safe_col} ORDER BY count DESC"
        rows = store.conn.execute(sql).fetchall()
        return {
            "sectors": [{"name": r[0], "count": r[1]} for r in rows if r[0]],
            "total_sectors": len(rows),
        }

    # 6. Normalizer Report
    @app.get(
        "/v1/report",
        tags=["Metadata"],
        summary="Compilation and Normalization report with LGD statistics",
    )
    @app.get(
        "/report",
        tags=["Metadata"],
        include_in_schema=False,
    )
    def get_report():
        if store.report is not None:
            return store.report.summary_dict()
        return {"notice": "No normalization report attached to active dataset"}

